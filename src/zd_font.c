uint8_t zd_font_row(unsigned char character, uint8_t row)
{
    static const uint8_t minus[7] = {0, 0, 0, 0x1F, 0, 0, 0};
    static const uint8_t underscore[7] = {0, 0, 0, 0, 0, 0, 0x1F};
    static const uint8_t period[7] = {0, 0, 0, 0, 0, 0, 0x04};
    static const uint8_t colon[7] = {0, 0x04, 0, 0, 0x04, 0, 0};
    static const uint8_t slash[7] = {0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10};
    static const uint8_t exclamation[7] = {0x04, 0x04, 0x04, 0x04, 0x04, 0, 0x04};
    static const uint8_t question[7] = {0x0E, 0x11, 0x01, 0x02, 0x04, 0, 0x04};
    static const uint8_t plus[7] = {0, 0x04, 0x04, 0x1F, 0x04, 0x04, 0};
    const uint8_t *glyph = NULL;

    if (row >= 7U) return 0U;
    if (character >= (unsigned char)'a' &&
        character <= (unsigned char)'z') {
        character = (unsigned char)(character - (unsigned char)'a' +
                                    (unsigned char)'A');
    }

    if (character >= (unsigned char)'A' &&
        character <= (unsigned char)'Z') {
        glyph = zd_font_letters_digits[character - (unsigned char)'A'];
    } else if (character >= (unsigned char)'0' &&
               character <= (unsigned char)'9') {
        glyph = zd_font_letters_digits[26U +
                                       character - (unsigned char)'0'];
    } else {
        switch (character) {
        case '-': glyph = minus; break;
        case '_': glyph = underscore; break;
        case '.': glyph = period; break;
        case ':': glyph = colon; break;
        case '/': glyph = slash; break;
        case '!': glyph = exclamation; break;
        case '?': glyph = question; break;
        case '+': glyph = plus; break;
        default: return 0U;
        }
    }

    return glyph[row];
}
